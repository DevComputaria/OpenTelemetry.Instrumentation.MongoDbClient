#!/usr/bin/env python3
"""Extracts OSSF Scorecard SARIF results and writes a detailed summary to GITHUB_STEP_SUMMARY."""

import json
import os
import sys
import textwrap


def load_sarif(path):
    with open(path) as f:
        return json.load(f)


def get_score_label(properties):
    score = properties.get("score")
    if score is not None:
        try:
            return f"{float(score):.0f}/10"
        except (ValueError, TypeError):
            return str(score)
    return "N/A"


def get_severity(rule):
    props = rule.get("properties", {})
    return props.get("problem.severity", "N/A").upper()


def get_security_severity(rule):
    props = rule.get("properties", {})
    return props.get("security-severity", "N/A")


def format_help(help_text):
    return textwrap.dedent(help_text).strip()


def main():
    if len(sys.argv) < 2:
        print("Usage: format-scorecard-summary.py <results.sarif>", file=sys.stderr)
        sys.exit(1)

    sarif_path = sys.argv[1]
    data = load_sarif(sarif_path)
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    out_fh = open(summary_path, "a") if summary_path else sys.stdout

    runs = data.get("runs", [])

    out_fh.write("## OSSF Scorecard Results\n\n")

    for run_idx, run in enumerate(runs):
        driver = run.get("tool", {}).get("driver", {})
        run_name = driver.get("name", "Scorecard")
        run_version = driver.get("semanticVersion", "N/A")
        automation_id = run.get("automationDetails", {}).get("id", "")

        # Determine category from automation ID
        category = "Unknown"
        for cat in ["local", "online-scm", "branch-protection"]:
            if cat in automation_id:
                category = cat.replace("-", " ").title()
                break

        rules_map = {}
        for rule in driver.get("rules", []):
            rules_map[rule["id"]] = rule

        results = run.get("results", [])

        out_fh.write(f"### {category} ({run_version})\n\n")
        out_fh.write(f"<details>\n<summary>Click to expand {category} results</summary>\n\n")

        for result in results:
            rule_id = result.get("ruleId", "N/A")
            rule = rules_map.get(rule_id, {})
            message = result.get("message", {}).get("text", "N/A")
            level = result.get("level", "unknown")
            props = rule.get("properties", {})

            score = get_score_label(props)
            severity = get_severity(rule)
            sec_severity = get_security_severity(rule)
            short_desc = rule.get("shortDescription", {}).get("text", "N/A")
            full_desc = rule.get("fullDescription", {}).get("text", "N/A")
            help_md = rule.get("help", {}).get("markdown", "")

            # Header
            severity_icon = {"error": "🔴", "warning": "🟡", "recommendation": "🔵"}.get(level, "⚪")
            out_fh.write(f"#### {severity_icon} **{short_desc}** — Score: **{score}**\n\n")

            out_fh.write(f"**Severity:** {severity} | **Security Severity:** {sec_severity}\n\n")
            out_fh.write(f"**Full Description:** {full_desc}\n\n")

            out_fh.write("**Message:**\n\n")
            out_fh.write(f"```\n{message}\n```\n\n")

            if help_md:
                out_fh.write("**Remediation:**\n\n")
                out_fh.write(help_md)
                out_fh.write("\n\n")

            out_fh.write("---\n\n")

        out_fh.write("</details>\n\n")

    out_fh.write("---\n")
    out_fh.write(
        "_Generated by [OSSF Scorecard](https://github.com/ossf/scorecard) "
        "— results published to GitHub Code Scanning._\n"
    )

    if summary_path:
        out_fh.close()
        print(f"Summary written to {summary_path}", file=sys.stderr)
    else:
        out_fh.flush()


if __name__ == "__main__":
    main()
